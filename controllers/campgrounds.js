module.exports.updateCampgrounds = async (req, res) => {
    const { id } = req.params;

    // 1. Execute MapTiler geocoding request first so geoData is defined
    const geoData = await maptilerClient.geocoding.forward(req.body.campground.location, { limit: 1 });

    // 2. Validate geocoding results
    if (!geoData.features?.length) {
        req.flash('error', 'Could not geocode that location. Please try again and enter a valid location.');
        return res.redirect(`/campgrounds/${id}/edit`);
    }

    // 3. Find campground document and check ownership
    const campground = await Campground.findById(id);
    if (!campground.author.equals(req.user._id)) {
        req.flash('error', 'You do not have permission to do that');
        return res.redirect(`/campgrounds/${id}`);
    }

    // 4. Update text fields, geometry, and location
    Object.assign(campground, req.body.campground);
    campground.geometry = geoData.features[0].geometry;
    campground.location = geoData.features[0].place_name;

    // 5. Append new uploaded images
    const imgs = req.files.map(f => ({ url: f.path, filename: f.filename }));
    campground.images.push(...imgs);
    await campground.save();

    // 6. Remove selected images from Cloudinary & Mongo if requested
    if (req.body.deleteImages) {
        for (let filename of req.body.deleteImages) {
            await cloudinary.uploader.destroy(filename);
        }
        await campground.updateOne({ $pull: { images: { filename: { $in: req.body.deleteImages } } } });
    }

    req.flash('success', 'Successfully updated campground');
    res.redirect(`/campgrounds/${campground._id}`);
};

